def replace_note_text(xml_bytes: bytes, new_text: str) -> bytes:
    root = ET.fromstring(xml_bytes)
    body_shape = None

    for sp in root.findall(".//p:sp", NS):
        ph = sp.find("./p:nvSpPr/p:nvPr/p:ph", NS)
        if ph is not None and ph.attrib.get("type") == "body":
            body_shape = sp
            break

    if body_shape is None:
        raise RuntimeError("Notes body placeholder not found")

    tx_body = body_shape.find("./p:txBody", NS)
    if tx_body is None:
        raise RuntimeError("Notes txBody not found")

    for child in list(tx_body):
        tx_body.remove(child)

    body_pr = ET.SubElement(tx_body, f"{{{A_NS}}}bodyPr")
    body_pr.tail = None
    ET.SubElement(tx_body, f"{{{A_NS}}}lstStyle")
    para = ET.SubElement(tx_body, f"{{{A_NS}}}p")
    run = ET.SubElement(para, f"{{{A_NS}}}r")
    text = ET.SubElement(run, f"{{{A_NS}}}t")
    text.text = new_text

    return ET.tostring(root, encoding="utf-8", xml_declaration=True)


def main() -> None:
    src_path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(r"E:\CA001\Infomat\output.pptx")
    dst_path = Path(sys.argv[2]) if len(sys.argv) > 2 else src_path
    backup_path = src_path.with_name("output_before_notes_rewrite.pptx")

    if not backup_path.exists():
        shutil.copy2(src_path, backup_path)

    with tempfile.NamedTemporaryFile(delete=False, suffix=".pptx", dir=str(dst_path.parent)) as tmp_file:
        tmp_path = Path(tmp_file.name)

    with zipfile.ZipFile(src_path, "r") as src, zipfile.ZipFile(tmp_path, "w", compression=zipfile.ZIP_DEFLATED) as dst:
        for item in src.infolist():
            data = src.read(item.filename)
            if item.filename.startswith("ppt/notesSlides/notesSlide") and item.filename.endswith(".xml"):
                slide_num = int(Path(item.filename).stem.replace("notesSlide", ""))
                new_text = NOTES.get(slide_num)
                if new_text:
                    data = replace_note_text(data, new_text)
            dst.writestr(item, data)

    if dst_path.exists() and dst_path != src_path:
        dst_path.unlink()
    shutil.move(tmp_path, dst_path)
    print(f"Rewrote notes from {src_path} to {dst_path}")
    print(f"Backup saved at {backup_path}")


if __name__ == "__main__":
    main()
